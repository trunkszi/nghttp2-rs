//! Procedural macros for compile-time `nghttp2` descriptors.
//!
//! `nghttp2` represents a header name and value as a length-delimited byte slice
//! (`nghttp2_nv`). Building those slices from string literals at runtime costs an
//! allocation and a copy per header. [`nv`] embeds the bytes in the binary
//! instead, so the safe wrapper can hand the C library pointers into static data.
//!
//! [`nghttp2_callbacks`] checks the callback names of a `SessionHandler` impl
//! before the `nghttp2` callback layer generates its trampolines.

use proc_macro::TokenStream;
use proc_macro2::TokenStream as TokenStream2;
use quote::quote;
use syn::{Ident, ImplItem, ItemImpl, LitByteStr, LitStr, Token, ext::IdentExt, parse_macro_input};

/// Expands `nv!("name", "value")` or `nv!("name", "value", no_index)` into a
/// static header field.
///
/// Both arguments must be string literals, and their bytes are embedded in the
/// binary. The expansion is a single expression that evaluates to a
/// `HeaderField<'static>`. Its `from_static` constructor sets
/// `NGHTTP2_NV_FLAG_NO_COPY_NAME | NGHTTP2_NV_FLAG_NO_COPY_VALUE`.
///
/// The optional `no_index` argument additionally sets
/// `NGHTTP2_NV_FLAG_NO_INDEX`, which keeps `nghttp2` from inserting the field
/// into its HPACK dynamic table.
///
/// The name must already be lowercase: `NGHTTP2_NV_FLAG_NO_COPY_NAME` skips the
/// library's downcasing. The bytes live in the binary, so they never expire; a
/// descriptor built from caller-owned buffers carries that obligation instead.
///
/// The expansion refers to the `nghttp2` crate by name and deliberately omits a
/// leading `::`, because the `nghttp2` crate is itself a caller and resolves its
/// own name through an internal alias. The calling module must have `nghttp2` in
/// scope.
///
/// ```text
/// let method = nv!(":method", "POST");
/// let cookie = nv!("cookie", "session=abc", no_index);
/// ```
#[proc_macro]
pub fn nv(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as NvInput);
    expand_nv(&input).into()
}

/// Rejects `SessionHandler` method names that the session cannot bind.
///
/// The `nghttp2` callback layer matches handler methods to the C callback
/// setters by name. A misspelled method would otherwise compile and then never
/// be installed, so this attribute checks every method in the annotated impl
/// block against the callback names the C library exposes and reports an error
/// at the method name for anything else. The trampolines that connect an
/// accepted impl block to the C callbacks are generated by that layer.
///
/// The accepted method names are `send`, `recv`, `on_frame_recv`,
/// `on_invalid_frame_recv`, `on_data_chunk_recv`, `before_frame_send`,
/// `on_frame_send`, `on_frame_not_send`, `on_stream_close`, `on_begin_headers`,
/// `on_header`, `on_header_rcbuf`, `on_invalid_header`, `select_padding`,
/// `data_source_read_length`, `on_begin_frame`, `send_data`, `pack_extension`,
/// `unpack_extension`, `on_extension_chunk_recv`, `error_callback2`, and
/// `rand`.
#[proc_macro_attribute]
pub fn nghttp2_callbacks(attr: TokenStream, item: TokenStream) -> TokenStream {
    match expand_callbacks(attr.into(), item.into()) {
        Ok(tokens) => tokens.into(),
        Err(error) => error.to_compile_error().into(),
    }
}

/// Callback methods that an `nghttp2` session can bind.
const SESSION_CALLBACKS: [&str; 22] = [
    "send",
    "recv",
    "on_frame_recv",
    "on_invalid_frame_recv",
    "on_data_chunk_recv",
    "before_frame_send",
    "on_frame_send",
    "on_frame_not_send",
    "on_stream_close",
    "on_begin_headers",
    "on_header",
    "on_header_rcbuf",
    "on_invalid_header",
    "select_padding",
    "data_source_read_length",
    "on_begin_frame",
    "send_data",
    "pack_extension",
    "unpack_extension",
    "on_extension_chunk_recv",
    "error_callback2",
    "rand",
];

#[derive(Debug)]
struct NvInput {
    name: LitStr,
    value: LitStr,
    has_no_index: bool,
}

impl syn::parse::Parse for NvInput {
    fn parse(input: syn::parse::ParseStream<'_>) -> syn::Result<Self> {
        let name: LitStr = input.parse()?;
        let _comma: Token![,] = input.parse()?;
        let value: LitStr = input.parse()?;

        let has_no_index = if input.peek(Token![,]) {
            let _comma: Token![,] = input.parse()?;
            let flag: Ident = input.parse()?;
            if flag != "no_index" {
                return Err(syn::Error::new(flag.span(), "expected `no_index`"));
            }
            true
        } else {
            false
        };

        if !input.is_empty() {
            return Err(syn::Error::new(
                input.span(),
                "unexpected tokens after the header field",
            ));
        }

        Ok(Self {
            name,
            value,
            has_no_index,
        })
    }
}

fn expand_nv(input: &NvInput) -> TokenStream2 {
    let name = LitByteStr::new(input.name.value().as_bytes(), input.name.span());
    let value = LitByteStr::new(input.value.value().as_bytes(), input.value.span());
    let flags = if input.has_no_index {
        quote!(nghttp2::nv::NvFlags::NO_COPY_NO_INDEX)
    } else {
        quote!(nghttp2::nv::NvFlags::NO_COPY)
    };

    quote! {
        nghttp2::nv::HeaderField::from_static(#name, #value, #flags)
    }
}

fn expand_callbacks(attr: TokenStream2, item: TokenStream2) -> syn::Result<TokenStream2> {
    validate_attribute_args(attr)?;
    let item: ItemImpl = syn::parse2(item).map_err(|error| {
        syn::Error::new(
            error.span(),
            "nghttp2_callbacks must be applied to an impl block",
        )
    })?;
    let item = validate_callback_impl(item)?;
    Ok(quote!(#item))
}

fn validate_attribute_args(attr: TokenStream2) -> syn::Result<()> {
    match attr.into_iter().next() {
        Some(token) => Err(syn::Error::new(
            token.span(),
            "nghttp2_callbacks does not take arguments",
        )),
        None => Ok(()),
    }
}

fn validate_callback_impl(item: ItemImpl) -> syn::Result<ItemImpl> {
    for impl_item in &item.items {
        let ImplItem::Fn(method) = impl_item else {
            continue;
        };
        let name = method.sig.ident.unraw().to_string();
        if !SESSION_CALLBACKS.contains(&name.as_str()) {
            return Err(syn::Error::new(
                method.sig.ident.span(),
                format!("unknown session callback `{name}`"),
            ));
        }
    }
    Ok(item)
}

#[cfg(test)]
mod tests {
    use super::*;

    const VALID_IMPL: &str = "
        impl SessionHandler for Handler {
            fn send(&self) {}
            fn on_header(&self) {}
        }
    ";

    fn parse_nv(source: &str) -> syn::Result<NvInput> {
        syn::parse_str(source)
    }

    fn expansion_args(input: &NvInput) -> Vec<syn::Expr> {
        let expression: syn::Expr =
            syn::parse2(expand_nv(input)).expect("expansion parses as an expression");
        let syn::Expr::Call(call) = expression else {
            panic!("expansion is not a call expression");
        };
        call.args.into_iter().collect()
    }

    fn byte_string(expression: &syn::Expr) -> Vec<u8> {
        let syn::Expr::Lit(syn::ExprLit {
            lit: syn::Lit::ByteStr(bytes),
            ..
        }) = expression
        else {
            panic!("expected a byte string literal, got {expression:?}");
        };
        bytes.value()
    }

    #[test]
    fn nv_input_parses_two_arguments() {
        let parsed = parse_nv(r#"":method", "POST""#).expect("two literals parse");
        assert_eq!(parsed.name.value(), ":method");
        assert_eq!(parsed.value.value(), "POST");
        assert!(!parsed.has_no_index);
    }

    #[test]
    fn nv_input_parses_no_index() {
        let parsed = parse_nv(r#""cookie", "session=abc", no_index"#).expect("three tokens parse");
        assert_eq!(parsed.name.value(), "cookie");
        assert_eq!(parsed.value.value(), "session=abc");
        assert!(parsed.has_no_index);
    }

    #[test]
    fn nv_input_accepts_empty_literals() {
        let parsed = parse_nv("\"\", \"\"").expect("empty literals are string literals");
        assert_eq!(parsed.name.value(), "");
        assert_eq!(parsed.value.value(), "");

        let args = expansion_args(&parsed);
        assert_eq!(byte_string(&args[0]), b"");
        assert_eq!(byte_string(&args[1]), b"");
    }

    #[test]
    fn nv_input_rejects_trailing_tokens() {
        assert!(parse_nv(r#"":method", "POST", "extra""#).is_err());
        assert!(parse_nv(r#"":method", "POST" "extra""#).is_err());
        assert!(parse_nv(r#"":method", "POST","#).is_err());
    }

    #[test]
    fn nv_input_rejects_a_missing_value() {
        assert!(parse_nv(r#"":method""#).is_err());
        assert!(parse_nv(r#"":method","#).is_err());
    }

    #[test]
    fn nv_input_rejects_a_non_literal_name() {
        assert!(parse_nv(r#"method, "POST""#).is_err());
        assert!(parse_nv(r#"42, "POST""#).is_err());
    }

    #[test]
    fn nv_input_rejects_byte_string_literals() {
        assert!(parse_nv("b\":method\", \"POST\"").is_err());
        assert!(parse_nv("\":method\", b\"POST\"").is_err());
    }

    #[test]
    fn nv_input_rejects_an_uppercase_no_index_flag() {
        let error = parse_nv(r#"":method", "POST", NO_INDEX"#).expect_err("flags are lowercase");
        assert!(error.to_string().contains("no_index"), "{error}");
    }

    #[test]
    fn nv_input_rejects_an_unknown_third_identifier() {
        let error =
            parse_nv(r#"":method", "POST", index"#).expect_err("only `no_index` is accepted");
        assert!(error.to_string().contains("no_index"), "{error}");
    }

    #[test]
    fn nv_input_rejects_tokens_after_no_index() {
        assert!(parse_nv(r#"":method", "POST", no_index, "extra""#).is_err());
    }

    #[test]
    fn expand_nv_without_no_index_selects_no_copy() {
        let parsed = parse_nv(r#"":method", "POST""#).expect("parse");
        let tokens = expand_nv(&parsed).to_string();
        assert!(tokens.starts_with("nghttp2"), "{tokens}");
        assert!(tokens.contains("HeaderField :: from_static"), "{tokens}");
        assert!(tokens.contains("NvFlags :: NO_COPY"), "{tokens}");
        assert!(!tokens.contains("NO_COPY_NO_INDEX"), "{tokens}");
    }

    #[test]
    fn expand_nv_with_no_index_selects_no_copy_no_index() {
        let parsed = parse_nv(r#""cookie", "a=b", no_index"#).expect("parse");
        let tokens = expand_nv(&parsed).to_string();
        assert!(tokens.starts_with("nghttp2"), "{tokens}");
        assert!(tokens.contains("HeaderField :: from_static"), "{tokens}");
        assert!(tokens.contains("NvFlags :: NO_COPY_NO_INDEX"), "{tokens}");
    }

    #[test]
    fn expand_nv_decodes_escaped_literals() {
        let parsed = parse_nv(r#""a\tb", "c\nd""#).expect("escapes decode");
        assert_eq!(parsed.name.value(), "a\tb");
        assert_eq!(parsed.value.value(), "c\nd");

        let args = expansion_args(&parsed);
        assert_eq!(args.len(), 3);
        assert_eq!(byte_string(&args[0]), b"a\tb");
        assert_eq!(byte_string(&args[1]), b"c\nd");

        let parsed = parse_nv(r#""a\u{0}", "b\u{7f}c""#).expect("unicode escapes decode");
        let args = expansion_args(&parsed);
        assert_eq!(byte_string(&args[0]), b"a\0");
        assert_eq!(byte_string(&args[1]), b"b\x7fc");
    }

    #[test]
    fn expand_nv_keeps_multibyte_utf8_bytes() {
        let parsed = parse_nv(r#""x-café", "naïve ☕""#).expect("non-ASCII literals parse");
        let args = expansion_args(&parsed);
        assert_eq!(byte_string(&args[0]), "x-café".as_bytes());
        assert_eq!(byte_string(&args[1]), "naïve ☕".as_bytes());
    }

    #[test]
    fn callbacks_leave_a_valid_impl_unchanged() {
        let original: ItemImpl = syn::parse_str(VALID_IMPL).expect("impl parses");
        let validated = validate_callback_impl(original.clone()).expect("valid impl passes");
        assert_eq!(validated, original);
    }

    #[test]
    fn callbacks_attribute_emits_the_impl_unchanged() {
        let original: ItemImpl = syn::parse_str(VALID_IMPL).expect("impl parses");
        let expanded =
            expand_callbacks(TokenStream2::new(), quote!(#original)).expect("valid impl expands");
        let reparsed: ItemImpl = syn::parse2(expanded).expect("output is one impl block");
        assert_eq!(reparsed, original);
    }

    #[test]
    fn callbacks_check_names_regardless_of_the_implemented_trait() {
        let foreign: ItemImpl =
            syn::parse_str("impl Other for Handler { fn send(&self) {} }").expect("impl parses");
        assert!(validate_callback_impl(foreign).is_ok());

        let inherent: ItemImpl =
            syn::parse_str("impl Handler { fn on_headr(&self) {} }").expect("impl parses");
        let error = validate_callback_impl(inherent).expect_err("the check is name-based");
        assert!(error.to_string().contains("on_headr"), "{error}");
    }

    #[test]
    fn callbacks_ignore_non_function_impl_items() {
        let item: ItemImpl = syn::parse_str(
            "impl SessionHandler for Handler { const ID: u8 = 1; type Output = (); }",
        )
        .expect("impl parses");
        assert!(validate_callback_impl(item).is_ok());

        let item: ItemImpl = syn::parse_str(
            "impl SessionHandler for Handler { const ID: u8 = 1; fn on_headr(&self) {} }",
        )
        .expect("impl parses");
        assert!(validate_callback_impl(item).is_err());
    }

    #[test]
    fn callbacks_accept_raw_identifiers_without_rewriting_them() {
        let item: ItemImpl = syn::parse_str(
            "impl SessionHandler for Handler { fn r#send(&self) {} fn r#on_header(&self) {} }",
        )
        .expect("raw identifiers parse");
        assert_eq!(validate_callback_impl(item.clone()).unwrap(), item);
        let invalid: ItemImpl = syn::parse_str("impl Handler { fn r#on_headr(&self) {} }").unwrap();
        assert!(validate_callback_impl(invalid).is_err());
    }

    #[test]
    fn callbacks_reject_an_unknown_method_name() {
        let item: ItemImpl =
            syn::parse_str("impl SessionHandler for Handler { fn on_headr(&self) {} }")
                .expect("impl parses");
        let error = validate_callback_impl(item).expect_err("unknown method is rejected");
        assert!(error.to_string().contains("on_headr"), "{error}");
        assert!(
            error.to_string().contains("unknown session callback"),
            "{error}"
        );
    }

    #[test]
    fn callbacks_reject_a_non_impl_item() {
        let error = expand_callbacks(
            TokenStream2::new(),
            quote!(
                fn send(&self) {}
            ),
        )
        .expect_err("non-impl item is rejected");
        assert_eq!(
            error.to_string(),
            "nghttp2_callbacks must be applied to an impl block"
        );

        let error = expand_callbacks(
            TokenStream2::new(),
            quote!(
                trait SessionHandler {
                    fn send(&self) {}
                }
            ),
        )
        .expect_err("a trait definition is rejected");
        assert_eq!(
            error.to_string(),
            "nghttp2_callbacks must be applied to an impl block"
        );
    }

    #[test]
    fn callbacks_reject_attribute_arguments() {
        let item: ItemImpl = syn::parse_str(VALID_IMPL).expect("impl parses");
        let error = expand_callbacks(quote!(no_index), quote!(#item))
            .expect_err("attribute arguments are rejected");
        assert_eq!(
            error.to_string(),
            "nghttp2_callbacks does not take arguments"
        );
    }

    #[test]
    fn callback_allowlist_is_complete_and_unique() {
        let mut actual = SESSION_CALLBACKS;
        actual.sort_unstable();

        let mut expected = [
            "send",
            "recv",
            "on_frame_recv",
            "on_invalid_frame_recv",
            "on_data_chunk_recv",
            "before_frame_send",
            "on_frame_send",
            "on_frame_not_send",
            "on_stream_close",
            "on_begin_headers",
            "on_header",
            "on_header_rcbuf",
            "on_invalid_header",
            "select_padding",
            "data_source_read_length",
            "on_begin_frame",
            "send_data",
            "pack_extension",
            "unpack_extension",
            "on_extension_chunk_recv",
            "error_callback2",
            "rand",
        ];
        expected.sort_unstable();

        assert_eq!(actual, expected);
    }
}
